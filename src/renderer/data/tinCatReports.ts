export interface TinCatScanRecord {
  id: number;
  cycleId: number;
  assetCode: string;
  scannedBy: string;
  scannedAt: string;
  edits?: { originalAssetCode: string; newAssetCode: string; reason: string; editedBy: string; editedAt: string }[];
}

export const matchesTinCatSearch = (scan: TinCatScanRecord, search: string) =>
  [scan.assetCode, scan.scannedBy, String(scan.cycleId), ...(scan.edits || []).flatMap((edit) => [edit.originalAssetCode, edit.newAssetCode, edit.reason, edit.editedBy])]
    .some((value) => value.toLowerCase().includes(search.trim().toLowerCase()));

const escapeHtml = (value: unknown) => String(value ?? '').replace(/[&<>"']/g, (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[character]!));

export function buildTinCatReportHtml(scans: TinCatScanRecord[], title: string, period: string, generatedBy: string) {
  const rows = scans.map((scan) => `<tr><td>${escapeHtml(scan.assetCode)}</td><td>${scan.cycleId}</td><td>${escapeHtml(scan.scannedAt)}</td><td>${escapeHtml(scan.scannedBy)}</td><td>${(scan.edits || []).map((edit) => `${escapeHtml(edit.originalAssetCode)} &rarr; ${escapeHtml(edit.newAssetCode)}<br>${escapeHtml(edit.reason)}<br>${escapeHtml(edit.editedBy)} · ${escapeHtml(edit.editedAt)}`).join('<hr>') || 'None'}</td></tr>`).join('');
  return `<!DOCTYPE html><html><head><meta charset="utf-8"><title>${escapeHtml(title)}</title><style>
    @page { size: landscape; margin: 12mm; } body { font: 11px sans-serif; color: #172329; } h1 { font-size: 22px; margin-bottom: 6px; }
    table { width: 100%; border-collapse: collapse; } th, td { padding: 7px; border: 1px solid #bbb; text-align: left; vertical-align: top; overflow-wrap: anywhere; }
    thead { display: table-header-group; } tr { break-inside: avoid; } th { background: #edf3f1; } .meta { margin-bottom: 16px; }
    </style></head><body><h1>OpsIQ Food Safety / ${escapeHtml(title)}</h1><div class="meta">${escapeHtml(period)}<br>${scans.length} inspections · ${new Set(scans.map((scan) => scan.cycleId)).size} cycles<br>Generated by ${escapeHtml(generatedBy)} · ${escapeHtml(new Date().toLocaleString())}</div>
    <table><thead><tr><th>Tin Cat</th><th>Cycle</th><th>Original Scan Date / Time</th><th>Scanned By</th><th>Corrections / Audit</th></tr></thead><tbody>${rows}</tbody></table></body></html>`;
}